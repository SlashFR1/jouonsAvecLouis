def clean_word(w):
    w = unicodedata.normalize('NFD', w).encode('ascii', 'ignore').decode('utf-8')
    w = w.strip().upper()
    return "".join(c for c in w if c.isalpha())

cleaned = set()
for w in raw_words:
    cw = clean_word(w)
    if 6 <= len(cw) <= 8:
        cleaned.add(cw)

sorted_words = sorted(list(cleaned))
print(f"Total mots generes: {len(sorted_words)}")

data = {
    "title": "Motus Loustic",
    "description": "Dictionnaire officiel de mots francais de 6 a 8 lettres pour Motus",
    "words": sorted_words
}

backend_path = "loustic-backend/src/main/resources/data/motus.json"
frontend_path = "loustic-frontend/src/data/motus.json"

with open(backend_path, "w", encoding="utf-8") as f:
    json.dump(data, f, ensure_ascii=False, indent=2)

with open(frontend_path, "w", encoding="utf-8") as f:
    json.dump(data, f, ensure_ascii=False, indent=2)

